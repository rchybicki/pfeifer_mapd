func applyMaxSpeedOverride(wayID int64, way *TmpWay) {
	overrideKph, ok := maxSpeedOverrides[wayID]
	if !ok {
		return
	}

	override := ms.KPH_TO_MS * overrideKph
	way.MaxSpeed = override

	if way.MaxSpeedForward > 0 {
		way.MaxSpeedForward = override
	}
	if way.MaxSpeedBackward > 0 {
		way.MaxSpeedBackward = override
	}
}
